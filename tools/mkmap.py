#!/usr/bin/env python3
"""Write the generated lists under docs/map/gen/ from the files themselves.

The hand-written maps under docs/map/ say where to look for what. The lists that would
go stale if written by hand are made here: every make target (the top-level Makefile and
any .mk file) with the scripts it runs, and heading anchors with line numbers for the big plans.

Nothing reads the clock; the output is sorted, so two runs give the same bytes.
Never opened or listed: build output, worktrees, tmp, ROMs, game data, external code.

Usage:
    python3 -I tools/mkmap.py            write docs/map/gen/*.md
    python3 -I tools/mkmap.py --check    write nothing; exit 1 when a file on disk differs
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GEN = REPO / "docs" / "map" / "gen"
# Folders that are never listed: volatile ones, game data and private or generated material.
NEVER_LIST = ("build", "build-*", ".claude/worktrees", "tmp", "temp", "runs", "dl", "cores", "vendor", ".venv",
              "roms", "sdmc", "__pycache__", "docs/map/gen")
SCRIPT_ROOTS = ("tools",)
SCRIPT_SUFFIXES = (".py", ".sh", ".mk")
# Folders listed one level further in no generated list (the folder generator is not kept here).
SPLIT_FOLDERS: tuple[str, ...] = ()
# The big documents whose sections are worth jumping into by line number.
# Add "docs/PLAN.md" here once the plan exists (item laz-10); a listed file that is missing fails the run.
ANCHOR_FILES: tuple[str, ...] = ("docs/PLAN.md",)
ANCHOR_DEPTH = 3
PURPOSE_WIDTH = 120
TARGET_RE = re.compile(r"^([A-Za-z0-9_.%/-]+(?:[ \t]+[A-Za-z0-9_.%/-]+)*)[ \t]*:(?![=:])")
HEADING_RE = re.compile(r"^(#{1,6}) +(.*\S)")


class MapError(Exception):
    """The repository cannot be listed, or a file the map needs is missing."""


def list_files() -> tuple[str, ...]:
    """Return every tracked or untracked-but-not-ignored file, as sorted repo paths, minus the never-list folders."""
    command = ["git", "-C", str(REPO), "ls-files", "-co", "--exclude-standard", "-z", "--", "."]
    command += [f":(exclude){folder}" for folder in NEVER_LIST]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise MapError("git ls-files failed: " + result.stderr.strip())
    return tuple(sorted(path for path in result.stdout.split("\0") if path and "__pycache__" not in path.split("/") and (REPO / path).is_file()))


def read_text(path: str) -> str:
    """Return a repo file's text; bytes that are not UTF-8 are replaced, not fatal."""
    return (REPO / path).read_text(encoding="utf-8", errors="replace")


def clean(text: str) -> str:
    """Return one tidy line: no table breakers, no back-ticks, cut to the purpose width."""
    line = " ".join(text.replace("|", "/").replace("`", "'").split())
    return line if len(line) <= PURPOSE_WIDTH else line[:PURPOSE_WIDTH - 1].rstrip() + "…"


def make_files(files: tuple[str, ...]) -> tuple[str, ...]:
    """Return the make files of the repo."""
    return tuple(path for path in files if path == "Makefile" or path.endswith(".mk"))


def make_targets(files: tuple[str, ...]) -> dict[str, tuple[str, str]]:
    """Return {target: (make file, recipe text)} for every explicit target in the repo's make files."""
    targets: dict[str, tuple[str, str]] = {}
    for path in make_files(files):
        current: list[str] = []
        for line in read_text(path).split("\n"):
            match = TARGET_RE.match(line)
            if match and not line.startswith(("\t", " ", "#", "export", "ifeq", "ifneq", "define")):
                current = [name for name in match.group(1).split() if "%" not in name and "/" not in name
                           and "." not in name]
                for name in current:
                    targets.setdefault(name, (path, ""))
                rest = line.split(":", 1)[1]
                for name in current:
                    targets[name] = (targets[name][0], targets[name][1] + rest + "\n")
            elif line.startswith("\t") and current:
                for name in current:
                    targets[name] = (targets[name][0], targets[name][1] + line + "\n")
            elif line.strip() and not line.startswith("#"):
                current = []
    return targets


def short_list(entries: list[str], limit: int = 4) -> str:
    """Return the first few entries and a count of the rest."""
    if not entries:
        return "-"
    shown = ", ".join(entries[:limit])
    return shown if len(entries) <= limit else f"{shown} (+{len(entries) - limit} more)"


def header(title: str, note: str) -> list[str]:
    """Return the first lines every generated file carries."""
    return [f"# {title}", "", f"Generated by `python3 -I tools/mkmap.py`. Do not edit by hand. {note}", ""]


def render_targets(files: tuple[str, ...]) -> str:
    """Return every make target, the make file that defines it, and the scripts its recipe names."""
    targets = make_targets(files)
    lines = header("Every make target", "Scripts = the script paths the target's own recipe names.")
    lines += ["| Target | Defined in | Scripts |", "|---|---|---|"]
    for name in sorted(targets):
        path, recipe = targets[name]
        scripts = sorted(set(re.findall(r"tools/[\w./-]+\.(?:py|sh)", recipe)))
        lines.append(f"| `{name}` | `{path}` | {short_list(scripts, 6)} |")
    return "\n".join(lines) + "\n"


def render_anchors() -> str:
    """Return the headings of the big documents with their line numbers."""
    lines = header("Section anchors of the big documents",
                   f"Open a section with `sed -n 'START,ENDp' FILE`. Headings down to level {ANCHOR_DEPTH}.")
    for path in ANCHOR_FILES:
        if not (REPO / path).is_file():
            raise MapError(f"{path}: listed in ANCHOR_FILES of tools/mkmap.py but not on disk")
        text = read_text(path).split("\n")
        lines += [f"## `{path}` ({len(text)} lines)", ""]
        fenced = False
        for number, line in enumerate(text, 1):
            if line.startswith("```"):
                fenced = not fenced
            match = HEADING_RE.match(line)
            if match and not fenced and len(match.group(1)) <= ANCHOR_DEPTH:
                indent = "  " * (len(match.group(1)) - 1)
                lines.append(f"{indent}- {number}: {clean(match.group(2))}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_all() -> dict[str, str]:
    """Return {file name: text} for every generated file."""
    files = list_files()
    return {
        "targets.md": render_targets(files),
        "anchors.md": render_anchors(),
    }


def stale(pages: dict[str, str]) -> list[str]:
    """Return the generated files whose text on disk differs from the given text."""
    return [name for name, text in sorted(pages.items())
            if not (GEN / name).is_file() or (GEN / name).read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    """Write the generated lists, or check them."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a generated file is stale")
    args = parser.parse_args(argv)
    try:
        pages = render_all()
    except MapError as error:
        print(f"mkmap: {error}", file=sys.stderr)
        return 1
    if args.check:
        old = stale(pages)
        for name in old:
            print(f"mkmap: docs/map/gen/{name} is out of date; run python3 -I tools/mkmap.py", file=sys.stderr)
        return 1 if old else 0
    GEN.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(pages.items()):
        (GEN / name).write_text(text, encoding="utf-8")
        print(f"mkmap: wrote docs/map/gen/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
